def suma_numeros(a, b):
    """
    Esta función recibe dos números y devuelve su suma.
    
    Parámetros:
    a (int o float): El primer número.
    b (int o float): El segundo número.
    
    Retorna:
    int o float: La suma de los dos números.
    """
    return a + b

print(suma_numeros(5, 3))  # Ejemplo de uso de la función
print(suma_numeros(10.5, 4.5))  # Ejemplo de uso de la función con números flotantes